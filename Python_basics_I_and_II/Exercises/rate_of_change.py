# steady but negative rate of change 
def negative_change(x):
    return 5 - x
# This is negative but steady pace, here increasing the input causes the output to consistently decrease by a fixed amount. 

print(negative_change(5))

def contant_change(x):
    return 3 * x 

# this is constant, positive rate of change where the input steadly increase the output. 

def zero_rate(x):
    return 12 

print(zero_rate(45))
